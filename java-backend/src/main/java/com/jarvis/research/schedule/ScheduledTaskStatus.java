package com.jarvis.research.schedule;

/**
 * 定时任务自身的状态（不是单次执行的状态，那是 {@link TaskRunStatus}）。
 *
 * <p>刻意把"任务状态"和"执行状态"分成两个枚举：任务级只有三态，一次执行的结果
 * （成功/失败/超时/跳过）落在执行历史里。否则任务级状态会被最近一次执行反复污染，
 * 用户看到"我的任务失败了"却分不清是任务配置坏了还是这一次恰好赶上了上游抖动。</p>
 */
public enum ScheduledTaskStatus {

    /** 已注册进调度器，nextRunAt 非空。 */
    ACTIVE,

    /**
     * 已从调度器移出，不再自动触发；nextRunAt 置空。
     *
     * <p>手动"立即执行"不受此状态限制 —— 暂停的语义是"别自动跑"，不是"不许跑"。</p>
     */
    PAUSED,

    /**
     * 软删：同样从调度器移出，但记录保留。
     *
     * <p>不做物理删除是因为执行历史靠外键挂在任务上，物理删会级联带走历史，
     * 而验收明确要求"记录执行历史与异常"。列表查询默认过滤掉本状态。</p>
     */
    DELETED
}
