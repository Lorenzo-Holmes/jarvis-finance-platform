package com.jarvis.research.notification;

/**
 * 通知的类型：决定"这条通知说的是什么事"。
 *
 * <p>与 {@link NotificationLevel} 分开是有意的：类型是**分类**（列表按它筛选/聚合），
 * 等级是**优先级**（列表按它排序）。例如"任务失败"和"风险命中"都是用户要看的，
 * 但风险命中更急 —— 这层区别用类型表达不出来，所以单列一个 level。</p>
 *
 * <p>当前只收三类事件，都是"用户不主动看就永远不知道"的那种：
 * 任务失败、任务被自动暂停、风险检测命中。**成功不通知**（见 PRD 通知机制一节：
 * "高风险事件优先提醒"；每天一条"任务成功"只会把真正重要的通知淹掉）。</p>
 */
public enum NotificationType {

    /** 单次执行失败（含超时）——原因见 body，详情看执行历史。 */
    TASK_FAILED,

    /**
     * 连续失败达阈值，任务已被自动暂停。
     *
     * <p>这一类格外重要：任务一旦被自动暂停就**不会再自动跑**，
     * 而用户界面上它只是从 ACTIVE 变成 PAUSED —— 不主动通知，
     * 用户会以为它还在正常工作。</p>
     */
    TASK_AUTO_PAUSED,

    /** 风险检测命中（维持担保比例低于警戒线）。 */
    RISK_ALERT,

    /** AI 分析识别出的高风险/重要资讯事件。 */
    NEWS_ALERT
}
